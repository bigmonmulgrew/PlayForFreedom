using UnityEngine;

public class AsunaIdle : StateMachineBehaviour
{
    [Range(1, 50)]
    [SerializeField] int maxStates = 1;


    private static readonly int IdleStyleHash = Animator.StringToHash("IdleStyle");

    // OnStateEnter is called when a transition starts and the state machine starts to evaluate this state
    override public void OnStateEnter(Animator animator, AnimatorStateInfo stateInfo, int layerIndex)
    {
        SetIdleStyle(animator);
    }

    private void SetIdleStyle(Animator animator = null)
    {
        if (maxStates <= 1) return;
        if (animator) animator.SetInteger(IdleStyleHash, Random.Range(0, maxStates));

    }

